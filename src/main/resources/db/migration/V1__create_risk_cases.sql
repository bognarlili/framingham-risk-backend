CREATE TABLE risk_cases (
    id UUID PRIMARY KEY,
    male INTEGER,
    age INTEGER NOT NULL,
    education INTEGER,
    current_smoker INTEGER,
    cigs_per_day INTEGER,
    bp_meds INTEGER,
    prevalent_stroke INTEGER,
    prevalent_hyp INTEGER,
    diabetes INTEGER,
    tot_chol DOUBLE PRECISION,
    sys_bp DOUBLE PRECISION,
    dia_bp DOUBLE PRECISION,
    bmi DOUBLE PRECISION,
    heart_rate DOUBLE PRECISION,
    glucose DOUBLE PRECISION,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT risk_cases_age_chk CHECK (age >= 0 AND age <= 120),
    CONSTRAINT risk_cases_male_chk CHECK (male IS NULL OR male IN (0, 1)),
    CONSTRAINT risk_cases_current_smoker_chk CHECK (current_smoker IS NULL OR current_smoker IN (0, 1)),
    CONSTRAINT risk_cases_bp_meds_chk CHECK (bp_meds IS NULL OR bp_meds IN (0, 1)),
    CONSTRAINT risk_cases_prevalent_stroke_chk CHECK (prevalent_stroke IS NULL OR prevalent_stroke IN (0, 1)),
    CONSTRAINT risk_cases_prevalent_hyp_chk CHECK (prevalent_hyp IS NULL OR prevalent_hyp IN (0, 1)),
    CONSTRAINT risk_cases_diabetes_chk CHECK (diabetes IS NULL OR diabetes IN (0, 1)),
    CONSTRAINT risk_cases_cigs_chk CHECK (cigs_per_day IS NULL OR cigs_per_day >= 0),
    CONSTRAINT risk_cases_education_chk CHECK (education IS NULL OR education > 0),
    CONSTRAINT risk_cases_tot_chol_chk CHECK (tot_chol IS NULL OR tot_chol > 0),
    CONSTRAINT risk_cases_sys_bp_chk CHECK (sys_bp IS NULL OR sys_bp > 0),
    CONSTRAINT risk_cases_dia_bp_chk CHECK (dia_bp IS NULL OR dia_bp > 0),
    CONSTRAINT risk_cases_bmi_chk CHECK (bmi IS NULL OR bmi > 0),
    CONSTRAINT risk_cases_heart_rate_chk CHECK (heart_rate IS NULL OR heart_rate > 0),
    CONSTRAINT risk_cases_glucose_chk CHECK (glucose IS NULL OR glucose > 0)
);

CREATE INDEX idx_risk_cases_created_at ON risk_cases (created_at DESC);
